def plain(lang, key):
    """Retorna o texto da chave sem o ícone/emoji inicial (ex.: '🎧 Arquivos' -> 'Arquivos').

    Substitui os antigos `.replace("🎧 ", "")` espalhados pela UI, que quebravam
    silenciosamente sempre que o emoji do dicionário era trocado.
    """
    text = I18N[lang][key]
    head, sep, tail = text.partition(" ")
    if sep and head and not any(ch.isalnum() for ch in head):
        return tail
    return text

